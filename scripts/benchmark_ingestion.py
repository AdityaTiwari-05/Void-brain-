"""
scripts/benchmark_ingestion.py
--------------------------------
End-to-end ingestion benchmark for Operation Abhedya-Chakra — Phase 1.

Measures
--------
  - File size and row count
  - Wall-clock ingestion time (seconds)
  - Rows/sec throughput
  - Peak RSS memory during ingestion (MB)
  - Resulting DuckDB file size (MB)
  - Rejected and duplicate counts
  - PASS / FAIL verdict vs configured threshold

Usage
-----
    python scripts/benchmark_ingestion.py --input data/raw/synthetic_2m.csv
    python scripts/benchmark_ingestion.py --input data/raw/synthetic_2m.csv --db-path :memory:

Output format
-------------
Structured JSON to stdout, human summary to stderr.
PASS/FAIL line is the last line printed to stdout for easy CI parsing.

HONESTY NOTE
------------
If the input file is synthetic (generated by generate_synthetic.py),
results are labelled SYNTHETIC.  Never claim the hackathon ≤60s target
is met without a real dataset.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
import threading
from pathlib import Path

# Ensure backend/ is importable
_backend = Path(__file__).resolve().parent.parent / "backend"
if str(_backend) not in sys.path:
    sys.path.insert(0, str(_backend))


def _count_csv_rows(path: Path) -> int:
    """Count data rows (header excluded) without loading into memory."""
    count = 0
    with path.open("rb") as fh:
        # Skip header
        fh.readline()
        for _ in fh:
            count += 1
    return count


def _peak_rss_mb(stop_event: threading.Event, result: list[float]) -> None:
    """Background thread: poll RSS every 50 ms, store peak in result[0]."""
    try:
        import psutil
        proc = psutil.Process(os.getpid())
        peak = proc.memory_info().rss
        while not stop_event.is_set():
            rss = proc.memory_info().rss
            if rss > peak:
                peak = rss
            stop_event.wait(0.05)
        result[0] = peak / (1024 * 1024)
    except ImportError:
        result[0] = -1.0  # psutil unavailable


def run_benchmark(input_path: Path, db_path_str: str | None = None) -> dict:
    from app.ingestion.engine import run_ingestion
    from app.config import get_settings

    settings = get_settings()
    threshold = settings.benchmark_threshold_rows_per_sec

    # Determine if synthetic
    label = "SYNTHETIC" if "synthetic" in input_path.name.lower() else "REAL"

    # File stats
    file_size_bytes = input_path.stat().st_size
    file_size_mb = file_size_bytes / (1024 * 1024)

    print(f"[benchmark] Counting rows in {input_path.name} …", file=sys.stderr)
    csv_rows = _count_csv_rows(input_path)
    print(f"[benchmark] {csv_rows:,} data rows, {file_size_mb:.1f} MB", file=sys.stderr)

    # DB path
    db_path = Path(db_path_str) if db_path_str else None

    # Start RSS monitor
    stop_evt = threading.Event()
    peak_rss_holder: list[float] = [0.0]
    monitor_thread = threading.Thread(
        target=_peak_rss_mb, args=(stop_evt, peak_rss_holder), daemon=True
    )
    monitor_thread.start()

    t0 = time.perf_counter()
    report = run_ingestion(input_file=input_path, db_path=db_path)
    elapsed = time.perf_counter() - t0

    stop_evt.set()
    monitor_thread.join(timeout=2)
    peak_rss = peak_rss_holder[0]

    # DuckDB file size (skip for :memory:)
    db_size_mb: float = -1.0
    if db_path_str != ":memory:":
        effective_db = db_path or settings.db_path
        if Path(str(effective_db)).exists():
            db_size_mb = Path(str(effective_db)).stat().st_size / (1024 * 1024)

    rows_per_sec = report.rows_seen / elapsed if elapsed > 0 else 0
    verdict = "PASS" if rows_per_sec >= threshold else "FAIL"

    result = {
        "label":              label,
        "input_file":         str(input_path),
        "file_size_mb":       round(file_size_mb, 2),
        "csv_rows":           csv_rows,
        "rows_seen":          report.rows_seen,
        "rows_loaded":        report.rows_loaded,
        "rows_rejected":      report.rows_rejected,
        "rows_duplicate":     report.rows_duplicate,
        "duration_seconds":   round(elapsed, 3),
        "rows_per_sec":       round(rows_per_sec, 1),
        "peak_rss_mb":        round(peak_rss, 1) if peak_rss > 0 else "NOT_MEASURED",
        "db_size_mb":         round(db_size_mb, 2) if db_size_mb >= 0 else "NOT_MEASURED",
        "threshold_rows_per_sec": threshold,
        "verdict":            verdict,
        "accounting_ok":      report.accounting_ok,
        "run_id":             report.run_id,
        "report_path":        report.report_path,
    }

    # Human summary to stderr
    print(
        f"\n{'='*60}\n"
        f"  BENCHMARK RESULT [{label}]\n"
        f"  rows/sec      : {rows_per_sec:,.0f}\n"
        f"  duration      : {elapsed:.2f}s\n"
        f"  rows seen     : {report.rows_seen:,}\n"
        f"  rows loaded   : {report.rows_loaded:,}\n"
        f"  rejected      : {report.rows_rejected:,}\n"
        f"  duplicates    : {report.rows_duplicate:,}\n"
        f"  peak RSS MB   : {result['peak_rss_mb']}\n"
        f"  DB size MB    : {result['db_size_mb']}\n"
        f"  threshold     : {threshold:,} rows/sec\n"
        f"  VERDICT       : {verdict}\n"
        f"{'='*60}",
        file=sys.stderr,
    )

    return result


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Abhedya-Chakra Phase 1 — Ingestion Benchmark"
    )
    parser.add_argument("--input",   required=True, help="Path to CSV file.")
    parser.add_argument("--db-path", default=None,  help="Override DB path (use :memory: for throwaway).")
    parser.add_argument("--log-level", default="WARNING",
                        choices=["DEBUG", "INFO", "WARNING", "ERROR"])
    args = parser.parse_args()

    import logging
    logging.basicConfig(
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        level=getattr(logging, args.log_level),
        stream=sys.stderr,
    )

    src = Path(args.input)
    if not src.exists():
        print(f"ERROR: File not found: {src}", file=sys.stderr)
        sys.exit(1)

    result = run_benchmark(src, args.db_path)
    print(json.dumps(result, indent=2))

    sys.exit(0 if result["verdict"] == "PASS" else 1)


if __name__ == "__main__":
    main()
